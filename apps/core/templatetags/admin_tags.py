@register.simple_tag
def get_app_meta(app_label):
    """
    Returns presentation metadata (icon, color, badge, gradient) for an app.
    """
    label = (app_label or '').lower()
    meta = APP_META.get(label, DEFAULT_META).copy()
    meta['icon_safe'] = mark_safe(meta['icon'])
    return meta
