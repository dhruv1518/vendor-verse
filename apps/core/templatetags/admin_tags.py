from django import template
from django.db import models
from django.utils.safestring import mark_safe

register = template.Library()


@register.simple_tag
def get_admin_kpis():
    """
    Returns platform key performance indicators for the admin dashboard.
    Safe against query errors or empty databases.
    """
    stats = {
        'total_users': 0,
        'total_vendors': 0,
        'pending_vendors': 0,
        'total_products': 0,
        'total_orders': 0,
        'pending_orders': 0,
        'total_revenue': 0,
        'pending_reviews': 0,
    }
    try:
        from apps.accounts.models import User
        stats['total_users'] = User.objects.count()
    except Exception:
        pass

    try:
        from apps.vendors.models import Vendor, VendorApplication
        stats['total_vendors'] = Vendor.objects.filter(is_approved=True).count()
        stats['pending_vendors'] = VendorApplication.objects.filter(status='PENDING').count()
    except Exception:
        pass

    try:
        from apps.products.models import Product
        stats['total_products'] = Product.objects.count()
    except Exception:
        pass

    try:
        from apps.orders.models import Order
        stats['total_orders'] = Order.objects.count()
        stats['pending_orders'] = Order.objects.filter(status__in=['PENDING', 'CONFIRMED']).count()
        rev = Order.objects.filter(payment_status='PAID').aggregate(models.Sum('total'))['total__sum']
        stats['total_revenue'] = rev or 0
    except Exception:
        pass

    try:
        from apps.reviews.models import Review
        stats['pending_reviews'] = Review.objects.filter(is_verified=False).count()
    except Exception:
        pass

    return stats


